/** ลิงก์เปิดนโยบาย (ใส่ในหน้าใดก็ได้ แล้วเรียก bindPolicyLinks) */
export const policyLink = (label = 'นโยบายความเป็นส่วนตัวและการรักษาความลับ') =>
  `<button type="button" class="policy-link" data-policy>🛡 ${label}</button>`;

/** เปิดหน้าต่างนโยบาย — เป็นชั้นแยก ใช้ได้ทั้งก่อนและหลังเข้าสู่ระบบ */
export function openPolicy() {
  const layer = document.createElement('div');
  layer.className = 'policy-mask';
  layer.innerHTML = `
    <div class="policy-box" role="dialog" aria-modal="true" aria-labelledby="policy-title">
      <div class="policy-head">
        <span id="policy-title">🛡 นโยบายความเป็นส่วนตัวและการรักษาความลับ</span>
        <button type="button" class="policy-x" aria-label="ปิด">✕</button>
      </div>
      <div class="policy-body">
        <h2>${POLICY.title}</h2>
        <h3>${POLICY.company}</h3>
        ${POLICY.intro.map((p) => `<p>${p}</p>`).join('')}
        <ol>${POLICY.rules.map((r) => `<li>${r}</li>`).join('')}</ol>
        <div class="policy-foot">
          <span>${POLICY.effective}</span>
          <span class="policy-sign">${POLICY.signer}<br>${POLICY.signerTitle}</span>
        </div>
      </div>
      <div class="policy-actions"><button type="button" class="btn btn-primary policy-ok">รับทราบ</button></div>
    </div>`;
  const close = () => { layer.remove(); removeEventListener('keydown', onKey, true); };
  const onKey = (e) => { if (e.key === 'Escape') { e.stopPropagation(); close(); } };
  layer.querySelector('.policy-x').onclick = close;
  layer.querySelector('.policy-ok').onclick = close;
  layer.onclick = (e) => { if (e.target === layer) close(); };
  addEventListener('keydown', onKey, true);
  document.body.appendChild(layer);
  layer.querySelector('.policy-ok').focus();
}

/** ผูกปุ่มลิงก์นโยบายทั้งหมดในหน้า */
export function bindPolicyLinks(root = document) {
  root.querySelectorAll('[data-policy]').forEach((b) => { b.onclick = openPolicy; });
}
